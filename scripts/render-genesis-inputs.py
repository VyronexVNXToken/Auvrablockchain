#!/usr/bin/env python3
"""Validate Auvra public genesis inputs and render upstream BSC genesis input files."""
import csv, re, sys
from pathlib import Path

if len(sys.argv) != 3:
    raise SystemExit("usage: render-genesis-inputs.py <upstream-genesis-repo> <chain-id>")
repo = Path(sys.argv[1]).resolve()
chain_id = int(sys.argv[2])
if not 1 <= chain_id <= 65535:
    raise SystemExit("Auvra Parlia system contract chain ID must fit uint16 (1..65535).")

root = Path(__file__).resolve().parents[1]
validator_file = root / "config/validators.testnet.conf"
holders_file = root / "config/initial-holders.testnet.csv"
if not validator_file.is_file():
    raise SystemExit("Missing config/validators.testnet.conf; copy the example and provide public validator data.")
if not holders_file.is_file():
    raise SystemExit("Missing config/initial-holders.testnet.csv; copy the example and provide approved faucet allocations.")

addr = re.compile(r"^0x[0-9a-fA-F]{40}$")
bls = re.compile(r"^(?:0x)?[0-9a-fA-F]{96}$")
validators = []
for n, raw in enumerate(validator_file.read_text().splitlines(), 1):
    line = raw.strip()
    if not line or line.startswith("#"): continue
    fields = [x.strip() for x in line.split(",")]
    if len(fields) != 5: raise SystemExit(f"{validator_file}:{n}: expected 5 comma-separated fields")
    consensus, fee, bsc_fee, power, bls_key = fields
    if not all(addr.fullmatch(x) for x in (consensus, fee, bsc_fee)):
        raise SystemExit(f"{validator_file}:{n}: invalid EVM address")
    if not power.isdigit() or int(power) <= 0:
        raise SystemExit(f"{validator_file}:{n}: votingPower must be a positive integer")
    if not bls.fullmatch(bls_key):
        raise SystemExit(f"{validator_file}:{n}: BLS public key must be 48-byte hex")
    validators.append(fields)
if len(validators) < 4:
    raise SystemExit("At least four validator entries are required for the Auvra public testnet.")
for col in range(3):
    values=[v[col].lower() for v in validators]
    if len(set(values)) != len(values):
        raise SystemExit("Validator consensus/fee addresses must be unique within each address column.")

holders=[]
with holders_file.open(newline="") as f:
    for n, row in enumerate(csv.reader(f), 1):
        if not row: continue
        row=[x.strip() for x in row]
        if row[0].startswith("#"): continue
        if len(row)!=2 or not addr.fullmatch(row[0]):
            raise SystemExit(f"{holders_file}:{n}: expected address,balance_wei")
        if not row[1].isdigit() or int(row[1]) <= 0:
            raise SystemExit(f"{holders_file}:{n}: balance_wei must be a positive integer")
        holders.append((row[0], int(row[1])))
if not holders:
    raise SystemExit("At least one explicit AUR testnet faucet/treasury allocation is required.")
if len({a.lower() for a,_ in holders}) != len(holders):
    raise SystemExit("Duplicate initial holder address.")

(repo / "validators.conf").write_text("\n".join(",".join(v) for v in validators)+"\n")
js = ["// Generated by Auvra scripts; contains public addresses and allocations only.", "const validators = ["]
for c, f, bf, power, key in validators:
    js.append("  { consensusAddr: %r, feeAddr: %r, bscFeeAddr: %r, votingPower: %s, bLSPublicKey: %r }," % (c,f,bf,power,key))
js += ["];", "const web3 = require('web3');", "const RLP = require('rlp');",
"function extraDataSerialize(vs) { return Buffer.concat(vs.map(v => Buffer.from(web3.utils.hexToBytes(v.consensusAddr)))); }",
"function generateExtraData(vs) { return Buffer.concat([Buffer.alloc(32), extraDataSerialize(vs), Buffer.alloc(65)]); }",
"function validatorUpdateRlpEncode(vs) { return web3.utils.bytesToHex(RLP.encode([0x00, vs.map(v => [v.consensusAddr, v.bscFeeAddr, v.feeAddr, v.votingPower, v.bLSPublicKey])])); }",
"const extraValidatorBytes = generateExtraData(validators);",
"const validatorSetBytes = validatorUpdateRlpEncode(validators);",
"module.exports = { extraValidatorBytes, validatorSetBytes };"]
(repo / "scripts/validators.js").write_text("\n".join(js)+"\n")
holder_js=["// Generated by Auvra scripts. Values are explicit AUR wei allocations.", "module.exports = ["]
for a, wei in holders:
    holder_js.append("  { address: %r, balance: BigInt(%r).toString(16) }," % (a,str(wei)))
holder_js += ["];"]
(repo / "scripts/init_holders.js").write_text("\n".join(holder_js)+"\n")
print(f"Validated {len(validators)} validators and {len(holders)} initial AUR allocations for chain ID {chain_id}.")
